def is_noindex(text: str) -> bool:
    return bool(re.search(r'<meta\s+name="robots"\s+content="[^"]*noindex', head_of(text)))


def sitemap(pages: list[Page]) -> str:
    rows = []
    for p in pages:
        rows.append(f"  <url>\n    <loc>{xml_escape(p.url)}</loc>\n"
                    f"    <lastmod>{p.modified.isoformat()}</lastmod>\n  </url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(rows) + "\n</urlset>\n")


def feed(pages: list[Page]) -> str:
    items = sorted((p for p in pages if p.is_article), key=lambda p: p.published, reverse=True)

    def rfc822(d: date) -> str:
        return format_datetime(datetime(d.year, d.month, d.day, 12, tzinfo=timezone.utc))

    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" '
        'xmlns:dc="http://purl.org/dc/elements/1.1/">',
        "  <channel>",
        f"    <title>{SITE_NAME}</title>",
        f"    <link>{BASE_URL}/</link>",
        f"    <description>Medical AI, imaging informatics, and clinical workflow automation, "
        f"by Dr. Bradley J. Erickson.</description>",
        "    <language>en-us</language>",
        f'    <atom:link href="{BASE_URL}/feed.xml" rel="self" type="application/rss+xml"/>',
        f"    <image><url>{BASE_URL}/apple-touch-icon.png</url><title>{SITE_NAME}</title>"
        f"<link>{BASE_URL}/</link></image>",
    ]
    if items:
        out.append(f"    <lastBuildDate>{rfc822(items[0].published)}</lastBuildDate>")
    for p in items:
        out += [
            "    <item>",
            f"      <title>{xml_escape(p.headline)}</title>",
            f"      <link>{xml_escape(p.url)}</link>",
            f'      <guid isPermaLink="true">{xml_escape(p.url)}</guid>',
            f"      <pubDate>{rfc822(p.published)}</pubDate>",
            "      <dc:creator>Bradley J. Erickson</dc:creator>",
        ]
        if p.category:
            out.append(f"      <category>{xml_escape(p.category)}</category>")
        out += [f"      <description>{xml_escape(p.description)}</description>", "    </item>"]
    out += ["  </channel>", "</rss>", ""]
    return "\n".join(out)


def ensure_robots_sitemap(check: bool) -> bool:
    robots = SITE_ROOT / "robots.txt"
    text = robots.read_text(encoding="utf-8") if robots.exists() else "User-agent: *\nDisallow:\n"
    line = f"Sitemap: {BASE_URL}/sitemap.xml"
    if line in text:
        return False
    if not check:
        robots.write_text(text.rstrip("\n") + f"\n\n{line}\n", encoding="utf-8")
    return True


