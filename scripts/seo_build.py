# Head edits
# ──────────────────────────────────────────────────────────────

def shorten_title(title: str) -> str:
    if len(title) > TITLE_MAX and title.endswith(TITLE_SUFFIX):
        return title.removesuffix(TITLE_SUFFIX)
    return title


def trim_description(desc: str) -> str:
    if len(desc) <= DESC_MAX:
        return desc
    # The byline is already on the page and in the structured data.
    desc = BYLINE_RE.sub("", desc).strip()
    if len(desc) <= DESC_MAX:
        return desc
    cut = desc[: DESC_MAX - 1]
    # Prefer ending on a full sentence if one ends late enough
    # (but not on "Dr." or an initial like "J.").
    stops = [m.end() - 1 for m in SENTENCE_END_RE.finditer(cut + " ")]
    if stops and stops[-1] >= 100:
        return cut[: stops[-1] + 1]
    return cut[: cut.rfind(" ")].rstrip(",;:—- ") + "…"


def attr(s: str) -> str:
    """Escape for a double-quoted attribute (leaves apostrophes readable)."""
    return html.escape(s, quote=False).replace('"', "&quot;")


def json_ld(page: Page) -> dict:
    website = {
        "@type": "WebSite",
        "@id": f"{BASE_URL}/#website",
        "url": f"{BASE_URL}/",
        "name": SITE_NAME,
        "description": SITE_TAGLINE,
        "publisher": {"@id": AUTHOR["@id"]},
        "inLanguage": "en",
    }
    if page.kind == "home":
        graph = [website, AUTHOR]
    elif page.kind == "about":
        graph = [AUTHOR, {
            "@type": "ProfilePage",
            "@id": page.url,
            "url": page.url,
            "name": page.headline,
            "mainEntity": {"@id": AUTHOR["@id"]},
            "isPartOf": {"@id": website["@id"]},
        }]
    elif page.kind == "papers":
        graph = [{
            "@type": "CollectionPage",
            "@id": page.url,
            "url": page.url,
            "name": page.headline,
            "description": page.description,
            "isPartOf": {"@id": website["@id"]},
        }]
    else:
        article = {
            "@type": "BlogPosting",
            "@id": f"{page.url}#article",
            "mainEntityOfPage": page.url,
            "url": page.url,
            "headline": page.headline[:110],
            "description": page.description,
            "image": [page.og_url],
            "datePublished": page.published.isoformat(),
            "dateModified": page.modified.isoformat(),
            "author": {k: AUTHOR[k] for k in ("@type", "@id", "name", "url")},
            "publisher": {"@id": AUTHOR["@id"]},
            "isPartOf": {"@id": website["@id"]},
            "inLanguage": "en",
        }
        if page.category:
            article["articleSection"] = page.category
        crumbs = {
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": f"{BASE_URL}/"},
                {"@type": "ListItem", "position": 2,
                 "name": "Papers of Note" if page.kind == "review" else "Articles",
                 "item": f"{BASE_URL}/papers-of-note.html" if page.kind == "review"
                         else f"{BASE_URL}/#articles"},
                {"@type": "ListItem", "position": 3, "name": page.headline},
            ],
        }
        graph = [article, crumbs, AUTHOR]
    return {"@context": "https://schema.org", "@graph": graph}


def build_block(page: Page, head: str) -> str:
    """Managed <head> block. `head` is the page head with the old block removed."""
    lines: list[str] = []

    wanted = {
        "og:site_name": SITE_NAME,
        "og:type": "article" if page.is_article else "website",
        "og:url": page.url,
        "og:title": page.headline,
        "og:description": page.description,
        "og:image": page.og_url,
        "twitter:card": "summary_large_image",
        "twitter:title": page.headline,
        "twitter:description": page.description,
        "twitter:image": page.og_url,
    }
    if page.is_article:
        wanted["article:author"] = "Dr. Bradley J. Erickson"
        wanted["article:published_time"] = page.published.isoformat()
    for key, value in wanted.items():
        if meta_content(head, key) is None:
            kind = "name" if key.startswith("twitter:") else "property"
            lines.append(f'<meta {kind}="{key}" content="{attr(value)}">')
    lines += [
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{attr(page.headline)} | {SITE_NAME}">',
        '<link rel="icon" href="/favicon.ico" sizes="any">',
        '<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">',
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
        f'<link rel="alternate" type="application/rss+xml" title="{SITE_NAME}" href="{BASE_URL}/feed.xml">',
    ]
    ld = json.dumps(json_ld(page), ensure_ascii=False, indent=2).replace("</", "<\\/")
    ld = "\n".join("    " + l for l in ld.splitlines())
    lines.append(f'<script type="application/ld+json">\n{ld}\n    </script>')
    body = "\n".join("    " + l for l in lines)
    return f"\n    {BLOCK_START}\n{body}\n    <!-- seo:end -->"


def rewrite_page(page: Page, text: str) -> str:
    text = BLOCK_RE.sub("", text)
    head_end = text.lower().find("</head>")
    head, rest = text[:head_end], text[head_end:]

    # X/Twitter reads name=, not property=.
    head = head.replace('<meta property="twitter:', '<meta name="twitter:')

    # Point social images at the generated card.
    head = re.sub(
        r'(<meta\s+(?:name|property)="(?:og:image|twitter:image)"\s+content=")[^"]*(")',
        rf"\g<1>{page.og_url}\g<2>", head,
    )

    new_title = shorten_title(page.title)
    if new_title != page.title:
        head = re.sub(r"<title>.*?</title>", lambda _: f"<title>{html.escape(new_title, quote=False)}</title>",
                      head, count=1, flags=re.S)
        page.title = new_title

    new_desc = trim_description(page.description)
    if new_desc != page.description:
        head = re.sub(r'(<meta\s+name="description"\s+content=")[^"]*(")',
                      lambda m: m.group(1) + attr(new_desc) + m.group(2), head, count=1)
        page.description = new_desc

    head = head.rstrip() + build_block(page, head) + "\n"
    return head + rest


