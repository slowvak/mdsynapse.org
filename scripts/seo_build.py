def _font(bold: bool, size: int):
    from PIL import ImageFont
    names = ["InterDisplay-Bold.otf"] if bold else ["Inter-Medium.otf"]
    candidates = [FONT_DIR / n for n in names] + [
        Path("/System/Library/Fonts/Supplemental/Arial Bold.ttf" if bold
             else "/System/Library/Fonts/Supplemental/Arial.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold
             else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    ]
    for c in candidates:
        if c.exists():
            return ImageFont.truetype(str(c), size)
    return ImageFont.load_default(size)


def _gradient(w: int, h: int, a: tuple, b: tuple):
    from PIL import Image
    grad = Image.linear_gradient("L").rotate(-90).resize((w, h))
    return Image.composite(Image.new("RGB", (w, h), b), Image.new("RGB", (w, h), a), grad)


def _logo(draw, x: int, y: int, s: float) -> None:
    """The site's nav logo (a synapse node), scaled from its 32px SVG."""
    def c(cx, cy, r, color=CYAN):
        draw.ellipse([x + (cx - r) * s, y + (cy - r) * s, x + (cx + r) * s, y + (cy + r) * s], fill=color)
    dim = tuple(int(v * 0.7 + n * 0.3) for v, n in zip(CYAN, NAVY_DARK))
    for (x1, y1, x2, y2) in ((16, 10.5, 16, 13), (16, 19, 16, 21.5), (10.5, 16, 13, 16), (19, 16, 21.5, 16)):
        draw.line([x + x1 * s, y + y1 * s, x + x2 * s, y + y2 * s], fill=CYAN, width=max(1, int(1.5 * s)))
    c(16, 8, 2.5); c(16, 24, 2.5); c(8, 16, 2.5, dim); c(24, 16, 2.5, dim); c(16, 16, 3)


def _wrap(draw, text: str, font, width: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for w in words:
        trial = f"{line} {w}".strip()
        if draw.textlength(trial, font=font) <= width:
            line = trial
        else:
            if line:
                lines.append(line)
            line = w
    if line:
        lines.append(line)
    return lines


def draw_card(page: Page, out: Path) -> None:
    from PIL import Image, ImageDraw
    W, H, pad = 1200, 630, 80
    img = _gradient(W, H, NAVY_DARK, NAVY_MED)
    d = ImageDraw.Draw(img)

    # Header: logo + wordmark
    _logo(d, pad - 6, 58, 2.2)
    brand = _font(True, 34)
    d.text((pad + 70, 66), "MDSynapse", font=brand, fill=WHITE)
    d.text((pad + 70 + d.textlength("MDSynapse", font=brand), 66), ".org", font=brand, fill=CYAN)

    # Category pill
    label = {"home": SITE_TAGLINE, "about": "About the author", "papers": "Paper reviews",
             "review": "Paper review"}.get(page.kind) or (page.category or "Article")
    pill_font = _font(False, 24)
    tw = d.textlength(label.upper(), font=pill_font)
    top = 170
    d.rounded_rectangle([pad, top, pad + tw + 36, top + 44], radius=22,
                        outline=CYAN, width=2)
    d.text((pad + 18, top + 8), label.upper(), font=pill_font, fill=CYAN)

    # Title, auto-sized to fit between the pill and the footer
    title = page.headline if page.kind != "home" else "Medical AI, imaging informatics and clinical automation"
    y = top + 76
    room = (H - 120) - y
    for size in (68, 60, 54, 48, 42):
        tf = _font(True, size)
        lines = _wrap(d, title, tf, W - 2 * pad)
        if len(lines) * int(size * 1.18) <= room:
            break
    else:
        keep = room // int(size * 1.18)
        lines = lines[:keep]
        lines[-1] = lines[-1].rstrip(".,;:") + "…"
    for ln in lines:
        d.text((pad, y), ln, font=tf, fill=WHITE)
        y += int(size * 1.18)

    # Footer: author + gradient rule
    foot = _font(False, 26)
    d.text((pad, H - 92), "Dr. Bradley J. Erickson", font=foot, fill=SILVER)
    url = "mdsynapse.org"
    d.text((W - pad - d.textlength(url, font=foot), H - 92), url, font=foot, fill=SILVER)
    img.paste(_gradient(W, 10, PURPLE, CYAN), (0, H - 10))

    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, optimize=True)


def draw_favicons(force: bool) -> list[Path]:
    from PIL import Image, ImageDraw
    targets = {
        "favicon.ico": None, "favicon-32.png": 32, "apple-touch-icon.png": 180,
    }
    written = []
    if not force and all((SITE_ROOT / n).exists() for n in targets):
        return written

    def icon(px: int, rounded: bool):
        big = px * 4
        im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        if rounded:
            d.rounded_rectangle([0, 0, big - 1, big - 1], radius=big // 5, fill=NAVY_DARK)
        else:
            d.ellipse([0, 0, big - 1, big - 1], fill=NAVY_DARK)
        _logo(d, big * 0.06, big * 0.06, big * 0.88 / 32)
        return im.resize((px, px), Image.LANCZOS)

    icon(256, False).save(SITE_ROOT / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    icon(32, False).save(SITE_ROOT / "favicon-32.png", optimize=True)
    icon(180, True).convert("RGB").save(SITE_ROOT / "apple-touch-icon.png", optimize=True)
    return [SITE_ROOT / n for n in targets]


