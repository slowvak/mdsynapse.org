"""
seo_build.py: regenerate the site's search and social metadata.

Run after publishing (publish.py calls it automatically), or by hand:

  uv run scripts/seo_build.py              # update everything
  uv run scripts/seo_build.py --check      # report what would change, write nothing
  uv run scripts/seo_build.py --force-images   # redraw every social card

What it does, for every indexable page (index, about, papers-of-note,
BlogPosts/*.html, Reviews/*.html; files starting with "_" are skipped):

  * Draws a branded 1200x630 social card at og/<name>.png if it is missing,
    and points og:image / twitter:image at it.
  * Writes a managed block before </head>, between <!-- seo:start --> and
    <!-- seo:end -->, holding JSON-LD structured data, favicon links, the
    RSS link, and any Open Graph / Twitter tags the page is missing.
    The block is rewritten on every run; edit this script, not the block.
  * Drops the " | MDSynapse.org" suffix from <title> when the title would
    otherwise exceed 60 characters, and trims meta descriptions over 160.
  * Writes sitemap.xml and feed.xml (RSS 2.0) at the site root.
  * Draws favicon.ico, favicon-32.png and apple-touch-icon.png if missing.

Every edit is idempotent: running it twice changes nothing the second time.
"""

