SITE_ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://mdsynapse.org"
SITE_NAME = "MDSynapse.org"
SITE_TAGLINE = "Think deep. Know more. Heal well."
TITLE_SUFFIX = " | MDSynapse.org"
TITLE_MAX = 60
DESC_MAX = 160

OG_DIR = SITE_ROOT / "og"
FONT_DIR = Path(__file__).resolve().parent / "fonts"

AUTHOR = {
    "@type": "Person",
    "@id": f"{BASE_URL}/#author",
    "name": "Bradley J. Erickson",
    "honorificPrefix": "Dr.",
    "honorificSuffix": "MD, PhD",
    "url": f"{BASE_URL}/about.html",
    "jobTitle": "Professor of Radiology",
    "affiliation": {"@type": "Organization", "name": "Mayo Clinic"},
    "sameAs": [
        "https://www.linkedin.com/in/bradleyerickson/",
        "https://www.mayo.edu/research/faculty/erickson-bradley-j-m-d-ph-d/bio-00077505",
    ],
}

# Brand colours, from styles.css
NAVY_DARK = (30, 27, 75)
NAVY_MED = (49, 46, 129)
CYAN = (6, 182, 212)
PURPLE = (139, 92, 246)
WHITE = (248, 250, 252)
SILVER = (148, 163, 184)

BYLINE_RE = re.compile(r"\s*By Dr\. Bradley J\. Erickson at mdsynapse\.org\.?\s*$")
SENTENCE_END_RE = re.compile(r"(?<!\bDr)(?<!\b[A-Z])[.?!](?=\s)")

BLOCK_START = "<!-- seo:start (generated by scripts/seo_build.py; edits here are overwritten) -->"
BLOCK_RE = re.compile(r"\n?[ \t]*<!-- seo:start.*?<!-- seo:end -->", re.S)


# ──────────────────────────────────────────────────────────────
# Page model
# ──────────────────────────────────────────────────────────────

@dataclass
class Page:
    path: Path
    kind: str                 # "home" | "about" | "papers" | "post" | "review"
    og_name: str              # og/<og_name>.png
    url: str = ""
    title: str = ""           # <title> text, unescaped
    headline: str = ""        # og:title or <h1>, unescaped
    description: str = ""
    category: str = ""
    published: date | None = None
    modified: date | None = None
    extra: dict = field(default_factory=dict)

    @property
    def is_article(self) -> bool:
        return self.kind in ("post", "review")

    @property
    def og_url(self) -> str:
        return f"{BASE_URL}/og/{self.og_name}.png"


def discover_pages() -> list[Page]:
    pages = [
        Page(SITE_ROOT / "index.html", "home", "home"),
        Page(SITE_ROOT / "about.html", "about", "about"),
        Page(SITE_ROOT / "papers-of-note.html", "papers", "papers"),
    ]
    for folder, kind in (("BlogPosts", "post"), ("Reviews", "review")):
        for p in sorted((SITE_ROOT / folder).glob("*.html")):
            if not p.name.startswith("_"):
                pages.append(Page(p, kind, p.stem))
    return pages


def head_of(text: str) -> str:
    end = text.lower().find("</head>")
    return text[:end] if end != -1 else ""


def meta_content(head: str, key: str) -> str | None:
    """Value of <meta name|property="key" content="...">, unescaped."""
    m = re.search(
        rf'<meta\s+(?:name|property)="{re.escape(key)}"\s+content="([^"]*)"', head
    )
    return html.unescape(m.group(1)) if m else None


def strip_tags(s: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def git_date(path: Path, first: bool = False) -> date | None:
    args = ["git", "log", "--format=%cs", "--", str(path.relative_to(SITE_ROOT))]
    if not first:
        args.insert(2, "-1")
    try:
        out = subprocess.run(args, cwd=SITE_ROOT, capture_output=True, text=True,
                             check=True).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        return None
    if not out:
        return None
    return date.fromisoformat(out[-1] if first else out[0])


def parse_display_date(s: str) -> date | None:
    try:
        return datetime.strptime(s.strip(), "%B %d, %Y").date()
    except ValueError:
        return None


def load(page: Page) -> str:
    text = page.path.read_text(encoding="utf-8")
    head = head_of(BLOCK_RE.sub("", text))

    canon = re.search(r'<link\s+rel="canonical"\s+href="([^"]+)"', head)
    page.url = canon.group(1) if canon else f"{BASE_URL}/{page.path.relative_to(SITE_ROOT).as_posix()}"

    t = re.search(r"<title>(.*?)</title>", head, re.S)
    page.title = html.unescape(t.group(1).strip()) if t else ""

    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", text, re.S)
    page.headline = (meta_content(head, "og:title")
                     or (strip_tags(h1.group(1)) if h1 else "")
                     or page.title.removesuffix(TITLE_SUFFIX))

    page.description = meta_content(head, "description") or ""

    cat = re.search(r'<div class="article-tag[^"]*">([^<]+)</div>', text)
    page.category = cat.group(1).strip() if cat else ""

    pub = meta_content(head, "article:published_time")
    if pub:
        page.published = date.fromisoformat(pub[:10])
    else:
        d = re.search(r'<span class="article-date">([^<]+)</span>', text)
        page.published = parse_display_date(d.group(1)) if d else None
    if page.is_article and page.published is None:
        page.published = git_date(page.path, first=True) or date.today()
    page.modified = git_date(page.path) or date.today()
    if page.published and page.modified < page.published:
        page.modified = page.published
    return text


