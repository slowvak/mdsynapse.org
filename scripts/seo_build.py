def write_if_changed(path: Path, content: str, check: bool, changed: list[str]) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != content:
        changed.append(str(path.relative_to(SITE_ROOT)))
        if not check:
            path.write_text(content, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="report changes without writing")
    ap.add_argument("--force-images", action="store_true", help="redraw all social cards and icons")
    args = ap.parse_args(argv)

    changed: list[str] = []
    warnings: list[str] = []
    pages: list[Page] = []

    for page in discover_pages():
        text = load(page)
        if is_noindex(text):
            continue
        new_text = rewrite_page(page, text)
        write_if_changed(page.path, new_text, args.check, changed)
        pages.append(page)

        card = OG_DIR / f"{page.og_name}.png"
        if args.force_images or not card.exists():
            changed.append(str(card.relative_to(SITE_ROOT)))
            if not args.check:
                draw_card(page, card)

        if len(page.title) > TITLE_MAX:
            warnings.append(f"{page.path.relative_to(SITE_ROOT)}: title is {len(page.title)} chars "
                            f"(Google shows about {TITLE_MAX}); consider a shorter one")
        if not page.description:
            warnings.append(f"{page.path.relative_to(SITE_ROOT)}: no meta description")

    write_if_changed(SITE_ROOT / "sitemap.xml", sitemap(pages), args.check, changed)
    write_if_changed(SITE_ROOT / "feed.xml", feed(pages), args.check, changed)
    if ensure_robots_sitemap(args.check):
        changed.append("robots.txt")
    if not args.check:
        changed += [str(p.relative_to(SITE_ROOT)) for p in draw_favicons(args.force_images)]

    verb = "Would change" if args.check else "Changed"
    print(f"SEO build: {len(pages)} pages. {verb} {len(changed)} file(s).")
    for c in changed:
        print(f"  {c}")
    for w in warnings:
        print(f"  NOTE: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
